// Re-export: blender -b kugoo_wish01.blend -P tools/kugoo/export.py -- kugoo.json && node tools/kugoo/pack.cjs kugoo.json src/game/kugooModel.js
// kugoo.json (from export.py) -> src/game/kugooModel.js: each group's triangles in the bike's own axes, around its pivot,
// quantized to 1/8000 m in Int16, with a byte of kind and a byte of hidden edges per triangle, base64 in the module
const fs = require('fs');
const j = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const OUT = process.argv[3];
const GK = { CHROME: 23, RUBBER: 24, DARK: 25, TIN: 36, YELLOW: 46, DASH: 33 };
const MAT = {
  Frame_White: 255, Battery_Cover: GK.DARK, Anodized_Black: GK.DARK, Aluminium: GK.TIN, Plastic_Gloss_Black: GK.RUBBER,
  Seat_Vinyl: GK.RUBBER, Caliper_Graphite: GK.DARK, Chrome: GK.CHROME, Spring_Black: GK.DARK, Plastic_Satin_Black: GK.DARK,
  Steel: GK.CHROME, Steel_Dark: GK.DARK, Fork_Gold: GK.YELLOW, Grip_Rubber: GK.RUBBER, Dash_Screen: GK.DASH, Tyre_Rubber: GK.RUBBER,
  Rim_Black: GK.DARK, none: GK.DARK,
};
const Q = 8000;
const groups = {};
const pivots = {};
for (const [g, T] of Object.entries(j.groups)) {
  const M = j.pivots[g];
  const t = [M[0][3], M[1][3], M[2][3]];
  pivots[g] = t.map((v) => +v.toFixed(4));
  const pos = new Int16Array(T.length * 9);
  const meta = new Uint8Array(T.length * 2);
  T.forEach((tri, i) => {
    for (let v = 0; v < 3; v++) {
      const x = tri[v * 3], y = tri[v * 3 + 1], z = tri[v * 3 + 2];
      // into the bike's axes (the pivot's rotation applied), the pivot's translation left out
      const bx = M[0][0] * x + M[0][1] * y + M[0][2] * z, by = M[1][0] * x + M[1][1] * y + M[1][2] * z, bz = M[2][0] * x + M[2][1] * y + M[2][2] * z;
      pos[i * 9 + v * 3] = Math.round(bx * Q); pos[i * 9 + v * 3 + 1] = Math.round(by * Q); pos[i * 9 + v * 3 + 2] = Math.round(bz * Q);
    }
    meta[i * 2] = MAT[tri[9]] ?? GK.DARK;
    meta[i * 2 + 1] = tri[10];
  });
  groups[g] = { n: T.length, p: Buffer.from(pos.buffer).toString('base64'), m: Buffer.from(meta).toString('base64') };
}
// the steering axis (the Steering empty's own Z, in the bike's axes): the bars turn about it, the fork slides along it
const S = j.pivots.steer;
const axis = [S[0][2], S[1][2], S[2][2]].map((v) => +v.toFixed(4));
const src = `// GENERATED by tools/kugoo/pack.cjs from the owner's kugoo_wish01.blend (Blender, procedural model, decimated
// for the game: bolts, nipples and rivets dropped, ~14.6k triangles). Do not edit by hand: re-export instead.
// Each group is in the bike's own axes (+x right, +y up, -z forward, ground at y = 0) around its pivot.
export const KUGOO_PIVOTS = ${JSON.stringify(pivots)};
export const KUGOO_STEER_AXIS = ${JSON.stringify(axis)};
export const KUGOO_Q = ${Q};
export const KUGOO_GROUPS = ${JSON.stringify(groups)};
`;
fs.writeFileSync(OUT, src);
console.log('wrote', OUT, (src.length / 1024).toFixed(0), 'KB', JSON.stringify(pivots), axis);
